def _write_pdf(path, sections):
    doc = SimpleDocTemplate(path, pagesize=A4, title=os.path.basename(path))
    story = []
    for heading, paragraphs in sections:
        story.append(Paragraph(heading, _TITLE))
        for paragraph in paragraphs:
            story.append(Paragraph(paragraph, _BODY))
        story.append(PageBreak())
    doc.build(story)


def _write_docx(path, sections):
    doc = DocxDocument()
    for heading, paragraphs in sections:
        doc.add_heading(heading, level=1)
        for paragraph in paragraphs:
            doc.add_paragraph(paragraph)
    doc.save(path)


def main():
    created = []
    for directory, filename, _, sections, meta in FILES:
        dir_path = os.path.join(SOURCES_ROOT, directory)
        os.makedirs(dir_path, exist_ok=True)
        path = os.path.join(dir_path, filename)
        if filename.endswith(".pdf"):
            _write_pdf(path, sections)
        else:
            _write_docx(path, sections)
        with open(path + ".meta.json", "w", encoding="utf-8") as handle:
            json.dump(meta, handle, ensure_ascii=False, indent=2)
        size = os.path.getsize(path)
        char_count = sum(len(p) for _, ps in sections for p in ps)
        created.append((path, size, char_count))
        print(f"{filename:20s} {size:>7d} bytes  约{char_count}字")
    return created


if __name__ == "__main__":
    main()
